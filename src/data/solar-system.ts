import { AU, DAY, DEG, EARTH_MASS, EARTH_RADIUS, SOLAR_MASS, SOLAR_RADIUS } from "@/engine/constants";
import type { CatalogBody } from "@/engine/types";

function orbit(
  aAU: number,
  e: number,
  iDeg: number,
  nodeDeg: number,
  periDeg: number,
  meanDeg: number,
) {
  return {
    a: aAU * AU,
    eccentricity: e,
    inclination: iDeg * DEG,
    longitudeAscending: nodeDeg * DEG,
    argPeriapsis: periDeg * DEG,
    meanAnomalyJ2000: meanDeg * DEG,
  };
}

function moonOrbit(aKm: number, e: number, iDeg: number, meanDeg: number, nodeDeg = 0, periDeg = 0) {
  return {
    a: aKm * 1000,
    eccentricity: e,
    inclination: iDeg * DEG,
    longitudeAscending: nodeDeg * DEG,
    argPeriapsis: periDeg * DEG,
    meanAnomalyJ2000: meanDeg * DEG,
  };
}

